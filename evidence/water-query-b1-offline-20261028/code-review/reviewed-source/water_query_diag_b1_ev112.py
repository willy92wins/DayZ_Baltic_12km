"""Strict B1 water-query data contract. Capture completeness is never map acceptance.

No file, engine or run identity is inferred here. A reviewed lifecycle binder must
verify those inputs before using this pure consumer on a native capture.
"""
import math
import re
import struct

COUNT = 115
ROUNDS = 3
SEA_REFS = ((2400., 7000.), (2430., 7020.), (2410., 7040.))
HEADER = 'BALTIC_WATER_QUERY_B1;BalticTrial'
STATE_KEYS = {'ground', 'roadway', 'water', 'rv', 'bullet'}


def require(ok, why):
    if not ok:
        raise ValueError(why)


def finite(v):
    value = float(v)
    require(math.isfinite(value), 'nonfinite')
    return value


def f32(v):
    result = struct.unpack('<f', struct.pack('<f', finite(v)))[0]
    require(math.isfinite(result), 'float32_overflow')
    return result


def integer(s):
    require(bool(re.fullmatch(r'0|[1-9][0-9]*', s)), 'integer')
    return int(s)


def boolean(s):
    require(s in ('true', 'false'), 'boolean')
    return s == 'true'


def vector(s):
    require(s.startswith('<') and s.endswith('>'), 'vector_delimiters')
    fields = s[1:-1].split(',')
    require(len(fields) == 3, 'vector_arity')
    return [finite(v.strip()) for v in fields]


def source_points(selected, original):
    """Bind selected A rows to the immutable 2658 result, retaining its verdicts."""
    require(original['status'] == 'FAIL' and original['points'] == 2658, 'original_verdict')
    rows = {r['id']: r for r in original['rows']}
    require(len(rows) == len(original['rows']) == 2658, 'original_ids')
    required = {v['id'] for v in original['failures']} | {v['id'] for v in original['inconclusive']}
    require(len(selected) == COUNT, 'source_count')
    ids = [r['id'] for r in selected]
    require(ids == sorted(set(ids)), 'source_order_or_duplicate')
    require(required <= set(ids) and len(required) == 68, 'source_required_coverage')
    result = []
    for r in selected:
        require(r['id'] in rows, 'source_id')
        orig = rows[r['id']]
        require(r['expected'] == orig['expected'] and r['original_states'] == orig['states'], 'source_binding')
        states = orig['states']
        require(set(states) == STATE_KEYS and set(states.values()) <= {'PASS', 'FAIL', 'INCONCLUSIVE'}, 'source_states')
        p = dict(orig['expected'])
        require(p['id'] == r['id'], 'source_inner_id')
        p['original_states'] = dict(states)
        for key in ('x', 'z', 'ground', 'roadway'):
            finite(p[key])
        for key in ('effective_bed', 'water_ext'):
            if p[key] is not None:
                finite(p[key])
        require(p['expect'] in ('dry', 'wet'), 'source_expect')
        result.append(p)
    require(sum(all(v == 'PASS' for v in p['original_states'].values()) for p in result) == 47, 'positive_count')
    return result


def csv_for(points):
    require(len(points) == COUNT, 'csv_count')
    lines = []
    for p in points:
        x, z = f32(p['x']), f32(p['z'])
        b, w = p['effective_bed'], p['water_ext']
        fields = [str(p['id']), f'{x:.9g} 0 {z:.9g}', f'{f32(b or 0):.9g}', f'{f32(w or 0):.9g}', str(int(b is not None)), str(int(w is not None))]
        lines.append(';'.join(fields))
    return '\n'.join(lines) + '\n'


def check_csv(csv, points):
    # Exact regenerated bytes, not merely a self-reported CSV checksum.
    require(csv == csv_for(points), 'csv_source_binding')


def surface_class(value, p, ground):
    matches = []
    for label, ref, band in (('WATER_REF', p['water_ext'], .05), ('BED_REF', p['effective_bed'], .03), ('GROUND_REF', ground, .01)):
        if ref is not None and abs(value - ref) <= band:
            matches.append(label)
    return dict(matches=matches, label='AMBIGUOUS' if len(matches) > 1 else matches[0] if matches else 'OTHER', identity='NOT_DETERMINED')


def near(a, b, band=.01):
    return len(a) == len(b) and all(abs(x-y) <= band for x, y in zip(a, b))


def parse(text, points):
    """Reject missing/extra records, duplicates, malformed native fields and clocks."""
    require(len(points) == COUNT and [p['id'] for p in points] == sorted({p['id'] for p in points}), 'point_universe')
    lines = text.splitlines()
    require(len(lines) >= 3 and lines[0] == HEADER and lines[1] == 'BEGIN;115;3' and lines[-1] == 'END;345', 'header_or_footer')
    cursor, last_end, result = 2, -1, []
    def fields(tag, size):
        nonlocal cursor
        require(cursor < len(lines)-1, 'truncated')
        a = lines[cursor].split(';')
        cursor += 1
        require(len(a) == size and a[0] == tag, 'record_schema:'+tag)
        return a
    for rnd in range(ROUNDS):
        for p in points:
            a = fields('Q', 26)
            require((integer(a[1]), integer(a[2])) == (rnd, p['id']), 'record_order')
            start, end = integer(a[3]), integer(a[4])
            require(start > last_end and end >= start, 'clock_order')
            last_end = end
            r = dict(id=p['id'], round=rnd, start_ms=start, end_ms=end, wave_before=finite(a[5]), wave_after=finite(a[6]), pos=vector(a[7]), ground=finite(a[8]), road=finite(a[9]), sea=boolean(a[10]), pond=boolean(a[11]), object_count=integer(a[12]), depth_origins=[vector(v) for v in a[13:16]], high=vector(a[16]), low=vector(a[17]), nf_high=finite(a[18]), fake_high=finite(a[19]), nf_low=finite(a[20]), fake_low=finite(a[21]), depths=[finite(v) for v in a[22:25]], low_below_ref=boolean(a[25]))
            require(r['object_count'] <= 10000, 'object_count_limit')
            objs = []
            for oi in range(r['object_count']):
                o = fields('O', 7)
                require(tuple(map(integer, o[1:4])) == (rnd, p['id'], oi), 'object_order')
                valid, shape, pos = boolean(o[4]), o[5], vector(o[6])
                require(valid or (not shape and pos == [0., 0., 0.]), 'null_object_payload')
                objs.append(dict(valid=valid, shape=shape, pos=pos))
            r['objects'] = objs
            refs = []
            for ri in range(3):
                s = fields('S', 11)
                require(tuple(map(integer, s[1:4])) == (rnd, p['id'], ri), 'sea_order')
                refs.append(dict(pos=vector(s[4]), sea=boolean(s[5]), pond=boolean(s[6]), nofake=finite(s[7]), fake=finite(s[8]), depth_origin=vector(s[9]), depth=finite(s[10])))
            r['sea_refs'] = refs
            result.append(r)
    require(cursor == len(lines)-1, 'extra_records')
    return result


def evaluate(points, rows):
    require(len(rows) == COUNT*ROUNDS, 'row_coverage')
    source = {p['id']: p for p in points}
    require(len(source) == COUNT, 'source_count')
    expected_keys = [(rnd, p['id']) for rnd in range(ROUNDS) for p in points]
    require([(r['round'], r['id']) for r in rows] == expected_keys, 'evaluation_order')
    mismatches, confounders, details, first = [], [], [], {}
    for r in rows:
        p = source[r['id']]
        x, z, h = f32(p['x']), f32(p['z']), r['ground']
        b = f32(p['effective_bed']) if p['effective_bed'] is not None else h
        water = f32(p['water_ext']) if p['water_ext'] is not None else None
        solid = max(h, b)
        upper = max(solid, water) if water is not None else solid
        desired = [[x, f32(f32(h)+f32(.01)), z], [x, f32(f32(solid)+f32(.01)), z], [x, f32(f32(upper)+f32(.25)), z]]
        require(near(r['pos'], [x, h, z]) and all(near(a, v) for a, v in zip(r['depth_origins'], desired)), 'query_origin')
        require(near(r['high'], [x, f32(f32(h)+100), z]) and near(r['low'], [x, f32(f32(solid)+2), z]), 'surface_origin')
        require(r['low_below_ref'] == (water is not None and water > f32(f32(solid)+2)), 'low_below_flag')
        key = dict(id=r['id'], round=r['round'])
        if abs(h-p['ground']) > .01:
            mismatches.append(dict(key, channel='ground', error=h-p['ground']))
        if p['original_states']['roadway'] != 'INCONCLUSIVE' and abs(r['road']-p['roadway']) > .03:
            mismatches.append(dict(key, channel='roadway', error=r['road']-p['roadway']))
        reasons = []
        if r['start_ms'] != r['end_ms'] or r['wave_before'] != r['wave_after']:
            reasons.append('query_clock_or_global_wave_changed')
        if r['low_below_ref']:
            reasons.append('low_origin_below_static_reference')
        if p['original_states']['roadway'] == 'INCONCLUSIVE':
            reasons.append('original_roadway_inconclusive')
        if any(not o['valid'] or not o['shape'] for o in r['objects']):
            reasons.append('object_snapshot_incomplete')
        for ri, ref in enumerate(r['sea_refs']):
            sx, sz = SEA_REFS[ri]
            require(near(ref['pos'], [sx, 100., sz]) and near(ref['depth_origin'], [sx, f32(f32(ref['nofake'])+.25), sz]), 'sea_origin')
            if not ref['sea'] or ref['pond']:
                reasons.append('sea_reference_flags')
        stable = {k:r[k] for k in ('pos', 'ground', 'road', 'sea', 'pond', 'object_count')}
        stable['objects'] = sorted((o['valid'], o['shape'], tuple(o['pos'])) for o in r['objects'])
        if r['id'] not in first:
            first[r['id']] = stable
        else:
            changed = [k for k in stable if stable[k] != first[r['id']][k]]
            if changed:
                reasons.append('round_state_drift:'+','.join(changed))
        confounders.extend(dict(key, reason=reason) for reason in reasons)
        surfaces = {k:r[k] for k in ('nf_high', 'fake_high', 'nf_low', 'fake_low')}
        residues = {k:[d-(v-pos[1]) for d, pos in zip(r['depths'], r['depth_origins'])] for k,v in surfaces.items()}
        details.append(dict(key, original_states=p['original_states'], original_expect=p['expect'], measured=r, surface_classes={k:surface_class(v, p, h) for k,v in surfaces.items()}, fake_minus_nofake=dict(high=r['fake_high']-r['nf_high'], low=r['fake_low']-r['nf_low']), depth_surface_residuals=residues, confounders=reasons))
    status = 'REFERENCE_MISMATCH' if mismatches else 'INCONCLUSIVE_DIAGNOSTIC' if confounders else 'CAPTURE_COMPLETE_DIAGNOSTIC_ONLY'
    return dict(status=status, rows=len(rows), reference_mismatches=mismatches, confounders=confounders, details=details, original_native_verdict='FAIL', product_reference='INCONCLUSIVE_PRODUCT_REFERENCE', surface_identity='INCONCLUSIVE', collision_b2='NOT_TESTED', scope='Selected server queries only. No map, visual, player or generator acceptance. Lifecycle identity must be bound separately.')


def consume(text, csv, selected, original):
    points = source_points(selected, original)
    check_csv(csv, points)
    return evaluate(points, parse(text, points))
